import assert from 'node:assert/strict';
import {experienceFields,experienceReady,experienceGaps} from '../src/experience/standards.js';
import {isActivityPublishable} from '../src/intelligence/publication.js';
import {journeyStage,preparationQueue,activityFeedback,feedbackQuestions} from '../src/experience/journey-operations.js';
import {trackedRequests} from '../src/portal/request-tracking.js';
const op={id:'op',publicationStatus:'approved'},a={title:'Nature walk',duration:'2 hours',operatorId:'op',publicationStatus:'approved'};
assert.equal(isActivityPublishable(a,[op]),false);
a.experienceDetails=Object.fromEntries(experienceFields.map(([k])=>[k,'Operator-supplied details']));
assert.equal(experienceReady(a),true);assert.equal(isActivityPublishable(a,[op]),true);
a.experienceDetails.accessibility=' ';assert.equal(experienceGaps(a).length,1);assert.equal(isActivityPublishable(a,[op]),false);
const b={id:'b',name:'Walk',status:'Confirmed',time:'09:00',date:'2026-11-20'};
const t={id:'t',status:'Confirmed',days:[{date:b.date,items:[b]}]};
assert.match(journeyStage(t,new Date('2026-11-20T12:00:00Z')).title,/adventure day/);
assert.match(journeyStage(t,new Date('2026-11-20T03:00:00Z')).title,/Get ready/);
assert.equal(preparationQueue([{...t,bookings:[b]}],new Date('2026-11-20T12:00:00Z'))[0].missing.length,4);
assert.equal(preparationQueue([{...t,status:'Cancelled',bookings:[b]}]).length,0);
const answers=Object.fromEntries(feedbackQuestions.map(([k])=>[k,'Yes']));
assert.throws(()=>activityFeedback(t,'b',2,answers,'Pickup was difficult'),/completed/);
b.status='Completed';const msg=activityFeedback(t,'b',2,answers,'Pickup was difficult');
assert.match(msg,/Experience follow-up/);assert.equal(trackedRequests([{id:'m',from:'customer',text:msg,at:'2026-11-20',user_id:'c'}]).length,1);
assert.throws(()=>activityFeedback(t,'unknown',5,answers,'Everything was excellent'),/completed/);
console.log('PASS: publication completeness, timezone-aware journey, readiness, completed-booking feedback and follow-up tracking.');
