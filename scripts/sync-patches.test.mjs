import assert from 'node:assert/strict';
import { createRecordSync, recordPatch } from '../src/admin/sync-patches.js';
assert.deepEqual(recordPatch({temperature:'Cold',name:'A'},{temperature:'Warm',name:'A'}).patch,{temperature:'Warm'});
let writes=[];
const sync=createRecordSync(async(id,patch,expected)=>{writes.push({id,patch,expected});});
sync.seed({a:{temperature:'Cold',name:'A'},b:{name:'B'}});
await sync.save({a:{temperature:'Warm',name:'A'},b:{name:'B'}});
assert.deepEqual(writes,[{id:'a',patch:{temperature:'Warm'},expected:{temperature:'Cold'}}]);
await sync.save({a:{temperature:'Warm',name:'A'},b:{name:'B'}});
assert.equal(writes.length,1);
await Promise.all([sync.save({a:{temperature:'Hot',name:'A'}}),sync.save({a:{temperature:'Cold',name:'A'}})]);
assert.equal(writes.at(-1).expected.temperature,'Hot');
const defaults=createRecordSync(async(id,patch,expected)=>assert.deepEqual(expected,{phone:null}));
defaults.seed({a:{phone:''}},{a:{}});
await defaults.save({a:{phone:'123'}});
let tries=0;
const failed=createRecordSync(async()=>{if(++tries===1)throw Error('conflict');});
failed.seed({a:{temperature:'Cold'}});
await assert.rejects(failed.save({a:{temperature:'Warm'}}),/conflict/);
await failed.save({a:{temperature:'Warm'}});
assert.equal(tries,2);
console.log('CRM sync: changed fields only, unchanged records skipped, queued updates ordered, database defaults handled, failures retained for retry.');
