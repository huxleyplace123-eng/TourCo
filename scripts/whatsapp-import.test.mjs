import assert from 'node:assert/strict';
import { splitWhatsAppChat, prepareWhatsAppNotes, MAX_CHAT_BYTES } from '../src/admin/whatsapp-import.js';
const android = '11/14/26, 12:41 PM - Adam: Hello\nSecond line\n11/14/26, 12:42 PM - John: Hi Adam';
assert.equal(splitWhatsAppChat(android).length, 2);
assert.match(splitWhatsAppChat(android)[0], /Second line$/);
const ios = '\u200e[14/11/2026, 12:41:00] Adam: Hello\n[14/11/2026, 12:42:00] John: Hi';
assert.equal(splitWhatsAppChat(ios).length, 2);
const first = await prepareWhatsAppNotes(android);
assert.equal(first.notes.length, 2);
const repeated = await prepareWhatsAppNotes(android.replaceAll('\n','\r\n'), first.notes);
assert.equal(repeated.notes.length, 0);
assert.equal(repeated.duplicates, 2);
const overlap = await prepareWhatsAppNotes(android + '\n11/14/26, 12:43 PM - Adam: Thanks', first.notes);
assert.equal(overlap.notes.length, 1);
assert.equal(overlap.duplicates, 2);
assert.equal((await prepareWhatsAppNotes('Plain pasted message')).notes.length, 1);
assert.equal((await prepareWhatsAppNotes('<script>alert(1)</script>')).notes[0].text, 'WhatsApp import (manual)\n<script>alert(1)</script>');
assert.throws(() => splitWhatsAppChat(' '));
assert.throws(() => splitWhatsAppChat('x'.repeat(MAX_CHAT_BYTES + 1)));
console.log('WhatsApp import: Android/iOS, multiline, overlapping exports, duplicates, plain text, and size limits passed.');
